def protected_development_years(manifest):
    """Source-bound by station identity too, so CSV conversion cannot relabel it."""
    source = manifest.get("source", {})
    known = source.get("repo") == "CMU-OSPO/protostar-climate-train-to-2018"
    known = known or bool(PROTECTED_CITIES.intersection(manifest.get("city_ids", [])))
    if not known:
        return []
    years = {origin + lead for origin in manifest["config"].get("development_origins", []) for lead in range(1, 8)}
    return sorted(years & PROTECTED_YEARS)


def enforce_phase_policy(manifest):
    overlap = protected_development_years(manifest)
    if overlap:
        raise ValueError(f"development targets overlap reserved assessment city-years {overlap}; changing suite roles does not authorize access")
